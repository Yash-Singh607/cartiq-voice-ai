// ─── Lookup helpers ───────────────────────────────────────────────────────────

export const PRODUCT_MAP = new Map<string, Product>(PRODUCTS.map(p => [p.id, p]))

export function getProductById(id: string): Product | undefined {
  return PRODUCT_MAP.get(id)
}

export function getSubstitutes(productId: string): Product[] {
  const p = PRODUCT_MAP.get(productId)
  if (!p) return []
  return (p.substituteIds?.map(id => PRODUCT_MAP.get(id)) ?? []).filter((p): p is Product => !!p)
}

export function getFrequentlyBoughtWith(productId: string): Product[] {
  const p = PRODUCT_MAP.get(productId)
  if (!p) return []
  return (p.frequentlyBoughtWith?.map(id => PRODUCT_MAP.get(id)) ?? []).filter((p): p is Product => !!p)
}

